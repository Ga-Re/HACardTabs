const LANGUAGES = { en, de };

function lookup(lang, key) {
  return key.split(".").reduce((obj, part) => (obj == null ? undefined : obj[part]), LANGUAGES[lang]);
}

export function language(hass) {
  const raw = hass?.locale?.language || hass?.language || navigator.language || "en";
  return raw.split("-")[0].toLowerCase();
}

export function localize(hass, key, vars) {
  const lang = language(hass);
  let text = lookup(lang, key) ?? lookup("en", key) ?? key;
  if (vars) {
    for (const [name, value] of Object.entries(vars)) {
      text = text.replace(`{${name}}`, value);
    }
  }
  return text;
}
